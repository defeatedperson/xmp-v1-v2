#!/bin/bash

set -e

# =============================================================================
# XMP 监控探针卸载脚本
# =============================================================================
# 环境变量说明：
#   SILENT  - 静默模式，不二次确认 (y/n)，默认 n
# =============================================================================

SERVICE_FILE="/etc/systemd/system/xmp-monitor.service"

# -----------------------------------------------------------------------------
# 错误退出函数
# -----------------------------------------------------------------------------
error_exit() {
    echo "错误: $1" >&2
    exit 1
}

# -----------------------------------------------------------------------------
# 检测 root 权限
# -----------------------------------------------------------------------------
if [ "$EUID" -ne 0 ]; then
    error_exit "请以 root 权限运行此脚本 (例如: sudo bash uninstall.sh)"
fi

# -----------------------------------------------------------------------------
# 检测服务是否存在
# -----------------------------------------------------------------------------
if [ ! -f "$SERVICE_FILE" ]; then
    error_exit "XMP 监控探针未安装 (未检测到 $SERVICE_FILE)"
fi

# -----------------------------------------------------------------------------
# 获取安装目录
# -----------------------------------------------------------------------------
INSTALL_DIR=$(grep "WorkingDirectory" "$SERVICE_FILE" | cut -d= -f2 | xargs)

if [ -z "$INSTALL_DIR" ] || [ ! -d "$INSTALL_DIR" ]; then
    error_exit "无法获取安装目录，请手动清理"
fi

# -----------------------------------------------------------------------------
# 确认卸载
# -----------------------------------------------------------------------------
SILENT="${SILENT:-n}"

if [ "$SILENT" != "y" ]; then
    echo "=========================================="
    echo " 警告：即将卸载 XMP 监控探针"
    echo "=========================================="
    echo ""
    echo "此操作将执行以下动作："
    echo "1. 停止并禁用 xmp-monitor 服务"
    echo "2. 删除系统服务文件"
    echo "3. 删除程序文件 (xmp-monitor)"
    echo "4. 删除证书目录 (cert)"
    echo "5. 删除配置文件 (.env)"
    echo "6. 删除数据目录 (monitor)"
    echo ""
    read -p "确认卸载？(y/n) [n]: " confirm
    if [ "$confirm" != "y" ]; then
        echo "已取消卸载"
        exit 0
    fi
fi

# -----------------------------------------------------------------------------
# 停止服务
# -----------------------------------------------------------------------------
echo "> 停止服务..."
systemctl stop xmp-monitor 2>/dev/null || true
systemctl disable xmp-monitor 2>/dev/null || true

# -----------------------------------------------------------------------------
# 删除 systemd 服务文件
# -----------------------------------------------------------------------------
echo "> 删除系统服务文件..."
rm -f "$SERVICE_FILE"
systemctl daemon-reload

# -----------------------------------------------------------------------------
# 终止残留进程
# -----------------------------------------------------------------------------
echo "> 终止残留进程..."
pkill -f xmp-monitor 2>/dev/null || true

# -----------------------------------------------------------------------------
# 删除文件
# -----------------------------------------------------------------------------
echo "> 删除程序文件..."
rm -f "$INSTALL_DIR/xmp-monitor"

echo "> 删除证书目录..."
rm -rf "$INSTALL_DIR/cert"

echo "> 删除数据目录..."
rm -rf "$INSTALL_DIR/monitor"

echo "> 删除配置文件..."
rm -f "$INSTALL_DIR/.env"

# -----------------------------------------------------------------------------
# 验证卸载结果
# -----------------------------------------------------------------------------
echo "> 验证卸载结果..."

UNINSTALL_SUCCESS=true

if systemctl is-active --quiet xmp-monitor 2>/dev/null; then
    echo "> 错误: 服务仍在运行"
    UNINSTALL_SUCCESS=false
fi

if [ -f "$INSTALL_DIR/xmp-monitor" ]; then
    echo "> 错误: 可执行程序未删除"
    UNINSTALL_SUCCESS=false
fi

if [ "$UNINSTALL_SUCCESS" = false ]; then
    error_exit "卸载验证失败"
fi

echo "> 卸载验证通过"

# -----------------------------------------------------------------------------
# 处理安装目录
# -----------------------------------------------------------------------------
REMAINING_FILES=$(ls -A "$INSTALL_DIR" 2>/dev/null | wc -l)
if [ "$REMAINING_FILES" -eq 0 ]; then
    rm -rf "$INSTALL_DIR"
    echo "> 已删除空安装目录: $INSTALL_DIR"
else
    echo "> 安装目录仍有文件保留: $INSTALL_DIR"
fi

# -----------------------------------------------------------------------------
# 完成
# -----------------------------------------------------------------------------
echo ""
echo "=========================================="
echo " XMP 监控探针卸载完成"
echo "=========================================="
echo "=========================================="
